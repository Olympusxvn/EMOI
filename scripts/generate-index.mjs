// Regenerate the repo symbol map (INDEX.md). Dependency-free, runs on plain Node.
// Usage: node scripts/generate-index.mjs [--check]
//   --check: exit 1 when INDEX.md differs from the generated output (for CI).
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(import.meta.url), "..", "..");
const SCAN_DIRS = ["agent/src", "agent/scripts", "agent/test", "contract/src", "frontend/src", "scripts"];
const EXT_RE = /\.(ts|tsx|rs|sh|mjs)$/;

// Heuristic export extractors (first match per line, good enough for a map).
const TS_EXPORT = /^\s*export\s+(?:async\s+)?(?:function|class|const|let|var|interface|type|enum)\s+([A-Za-z0-9_]+)/;
const TS_EXPORT_LIST = /^\s*export\s*\{([^}]+)\}/;
const RS_PUB = /^\s*pub\s+(?:async\s+)?(?:fn|struct|enum|trait|const|mod)\s+([A-Za-z0-9_]+)/;

function firstComment(lines) {
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith("#!")) continue;
    const m = line.match(/^(?:\/\/\/|\/\/|#|\/\*\*?|\*)\s?(.*?)(\*\/)?$/);
    if (m) {
      const text = (m[1] || "").trim();
      if (text) return text.slice(0, 100);
      continue;
    }
    return ""; // first code line reached: no header comment
  }
  return "";
}

function exportsOf(rel, text) {
  const names = [];
  for (const line of text.split("\n")) {
    let m;
    if (rel.endsWith(".rs")) {
      m = line.match(RS_PUB);
      if (m) names.push(m[1]);
    } else if (/\.(ts|tsx|mjs)$/.test(rel)) {
      m = line.match(TS_EXPORT);
      if (m) {
        names.push(m[1]);
        continue;
      }
      m = line.match(TS_EXPORT_LIST);
      if (m) {
        for (const part of m[1].split(",")) {
          const name = part.trim().split(/\s+as\s+/)[0].trim();
          if (name) names.push(name);
        }
      }
    }
  }
  if (rel.includes("/test/") && names.length === 0) return "(tests)";
  if (rel.endsWith(".sh") || rel.endsWith("generate-index.mjs")) return "(script)";
  return names.slice(0, 8).join(", ") + (names.length > 8 ? ", …" : "");
}

function walk(dir, out) {
  for (const entry of readdirSync(join(root, dir), { withFileTypes: true })) {
    if (entry.name.startsWith(".") || entry.name === "node_modules") continue;
    const rel = join(dir, entry.name).replace(/\\/g, "/");
    if (entry.isDirectory()) walk(rel, out);
    else if (EXT_RE.test(entry.name)) out.push(rel);
  }
  return out;
}

const files = [];
for (const dir of SCAN_DIRS) {
  if (existsSync(join(root, dir))) walk(dir, files);
}
files.sort();

const rows = files.map((rel) => {
  const text = readFileSync(join(root, rel), "utf8");
  const desc = firstComment(text.split("\n")).replaceAll("|", "\\|");
  return `| \`${rel}\` | ${exportsOf(rel, text) || "—"} | ${desc || "—"} |`;
});

const output = `# INDEX.md

> Auto-generated by \`node scripts/generate-index.mjs\`. DO NOT edit by hand.

| File | Export | Description |
|------|--------|-------------|
${rows.join("\n")}
`;

const indexPath = join(root, "INDEX.md");
if (process.argv.includes("--check")) {
  const current = existsSync(indexPath) ? readFileSync(indexPath, "utf8") : "";
  if (current !== output) {
    console.error("INDEX.md is stale. Run: node scripts/generate-index.mjs");
    process.exit(1);
  }
  console.log(`INDEX.md is fresh (${files.length} files).`);
} else {
  writeFileSync(indexPath, output);
  console.log(`Wrote INDEX.md (${files.length} files).`);
}
